"""Scan data/ and write docs/data_inventory.md (spec step 0). Never parses beyond headers and counts."""
from __future__ import annotations
import csv
import json
from pathlib import Path
from .. import config


def _row(p: Path) -> str:
    size = p.stat().st_size
    kind = p.suffix.lower().lstrip(".") or "file"
    detail = ""
    try:
        if kind == "csv":
            with open(p, newline="", encoding="utf-8-sig") as f:
                rows = list(csv.reader(f))
            detail = f"{max(len(rows) - 1, 0)} data rows; columns: {', '.join(rows[0][:12])}{' ...' if rows and len(rows[0]) > 12 else ''}" if rows else "empty"
        elif kind == "json":
            d = json.loads(p.read_text(encoding="utf-8"))
            detail = f"keys: {list(d)[:8]}; items: {len(d.get('items', []))}" if isinstance(d, dict) else f"list of {len(d)}"
        elif kind == "pdf":
            from pypdf import PdfReader
            r = PdfReader(str(p)); n = len(r.pages)
            txt = sum(1 for pg in r.pages[:5] if len((pg.extract_text() or "").strip()) > 20)
            detail = f"{n} pages; text found on {txt} of the first {min(n, 5)} pages"
        elif kind in ("xlsx", "xls"):
            import pandas as pd
            df = pd.read_excel(p, nrows=3, dtype=str); detail = f"columns: {', '.join(map(str, df.columns[:12]))}"
    except Exception as e:  # inventory must never crash on one bad file
        detail = f"could not read: {e}"
    return f"| {p.relative_to(config.ROOT)} | {size:,} | {kind} | {detail} |"


def build_inventory(out: Path | None = None) -> str:
    rows = [_row(p) for base in ("raw", "staging", "curated") for p in sorted((config.ROOT / "data" / base).rglob("*")) if p.is_file() and not p.name.startswith(".")]
    md = ["# Data inventory", "", "Generated by `python -m flare.cli inventory`. Raw files are read-only.", "",
          "| File | Bytes | Type | Contents |", "|---|---|---|---|", *rows, ""]
    text = "\n".join(md)
    (out or config.ROOT / "docs" / "data_inventory.md").write_text(text, encoding="utf-8")
    return text
