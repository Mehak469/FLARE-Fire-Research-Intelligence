"""Command line: python -m flare.cli <command>. See README.md."""
from __future__ import annotations
import argparse
import json
import sys
from pathlib import Path
from . import config
from .core import db as dbm
from .core.ask import ask
from .ingest.findings_import import import_findings
from .ingest.inventory import build_inventory
from .ingest.investigations import ingest_investigations
from .ingest.pdf_text import ingest_pdf
from .ingest.table_loader import load_table
from .ingest.verify import validate, verify_investigation_record, verify_runs

DEFAULT_MAPPING = config.CONFIG_DIR / "mappings" / "bass2.yaml"
DEFAULT_TABLE = config.ROOT / "data" / "staging" / "bass2_staging_sample.csv"


def _write_ingest_report(inv_rep=None, table_rep=None, val_rep=None, findings_rep=None) -> None:
    lines = ["# Ingest report", "", "Generated by the CLI. Flags are things a person must review; nothing was silently fixed.", ""]
    if inv_rep:
        lines += ["## Investigation records", f"- loaded: {inv_rep['loaded']}, declared ranges: {inv_rep['conditions']}, text chunks: {inv_rep['chunks']}"]
        lines += [f"- WARNING: {w}" for w in inv_rep["warnings"]]
    if table_rep:
        lines += ["", "## Experimental table", f"- rows in file: {table_rep['rows_in_file']}, loaded: {table_rep['loaded']}, skipped (already loaded): {table_rep['skipped_existing']}"]
        if table_rep["missing_columns"]:
            lines.append(f"- columns expected by the mapping but not found: {table_rep['missing_columns']}")
        lines += [f"- FLAG {f}" for f in table_rep["flags"]]
    if findings_rep:
        lines += ["", "## Curated findings", f"- read {findings_rep['read']}, inserted {findings_rep['inserted']}, skipped {findings_rep['skipped_existing']}, rejected {len(findings_rep['rejected'])}"]
        lines += [f"- REJECTED line {r['line']}: {r['reason']}" for r in findings_rep["rejected"]]
    if val_rep:
        lines += ["", "## Validation", f"- runs promoted to auto_checked: {val_rep['auto_checked']}"]
        lines += [f"- [{'ok' if c['ok'] else 'FAIL'}] {c['check']} {c['detail']}" for c in val_rep["checks"]]
    (config.ROOT / "docs" / "ingest_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def build_all(overwrite: bool = True) -> dict:
    conn = dbm.init_db(overwrite=overwrite)
    inv = ingest_investigations(conn)
    tab = load_table(conn, DEFAULT_MAPPING, DEFAULT_TABLE)
    fnd = import_findings(conn, config.ROOT / "data" / "curated" / "findings.csv")
    val = validate(conn)
    _write_ingest_report(inv, tab, val, fnd)
    return {"investigations": inv, "table": tab, "findings": fnd, "validation": val, "stats": dbm.stats(conn)}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="flare", description="FLARE command line")
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("init-db").add_argument("--overwrite", action="store_true")
    sub.add_parser("inventory")
    sub.add_parser("ingest-investigations")
    t = sub.add_parser("ingest-table"); t.add_argument("mapping"); t.add_argument("file")
    p = sub.add_parser("ingest-pdf"); p.add_argument("file"); p.add_argument("--source-key", required=True); p.add_argument("--title"); p.add_argument("--url")
    p.add_argument("--doi"); p.add_argument("--investigation"); p.add_argument("--year", type=int)
    f = sub.add_parser("import-findings"); f.add_argument("file", nargs="?", default=str(config.ROOT / "data" / "curated" / "findings.csv"))
    sub.add_parser("validate")
    v = sub.add_parser("verify"); v.add_argument("--investigation", required=True); v.add_argument("--labels", help="comma-separated run labels, e.g. B1,B2")
    v.add_argument("--by", required=True); v.add_argument("--apply", action="store_true"); v.add_argument("--accept-flags", action="store_true")
    v.add_argument("--record", action="store_true", help="verify the investigation record and its declared ranges instead of runs")
    sub.add_parser("build-all")
    a = sub.add_parser("ask"); a.add_argument("question"); a.add_argument("--offline", action="store_true")
    sub.add_parser("stats")
    sub.add_parser("eval")
    args = ap.parse_args(argv)

    if args.cmd == "init-db":
        dbm.init_db(overwrite=args.overwrite); print(f"created {config.DB_PATH}"); return 0
    if args.cmd == "inventory":
        print(build_inventory()); return 0
    if args.cmd == "build-all":
        r = build_all(); print(json.dumps(r["stats"], indent=2)); print("flags and validation: docs/ingest_report.md"); return 0
    conn = dbm.connect()
    if args.cmd == "ingest-investigations":
        rep = ingest_investigations(conn); print(rep); _write_ingest_report(inv_rep=rep)
    elif args.cmd == "ingest-table":
        rep = load_table(conn, Path(args.mapping), Path(args.file)); print({k: v for k, v in rep.items() if k != "flags"}); [print(" FLAG", x) for x in rep["flags"]]
    elif args.cmd == "ingest-pdf":
        print(ingest_pdf(conn, Path(args.file), args.source_key, args.title, args.url, args.doi, args.investigation, pub_year=args.year))
    elif args.cmd == "import-findings":
        rep = import_findings(conn, Path(args.file)); print(rep)
    elif args.cmd == "validate":
        rep = validate(conn); _write_ingest_report(val_rep=rep); [print(("ok  " if c["ok"] else "FAIL"), c["check"], c["detail"]) for c in rep["checks"]]
    elif args.cmd == "verify":
        if args.record:
            print("verified" if verify_investigation_record(conn, args.investigation, args.by) else "not found")
        else:
            for e in verify_runs(conn, args.investigation, (args.labels or "").split(","), args.by, args.accept_flags, args.apply):
                print(json.dumps(e, indent=1, default=str))
    elif args.cmd == "ask":
        r = ask(conn, args.question, use_llm=not args.offline)
        print(f"[{r['mode']}] {r['summary']}")
        for c in r["claims"]: print(f"  - ({c['evidence_label']}) {c['text']}  {c['evidence_ids']}")
        for l in r["limitations"]: print(f"  limitation: {l}")
    elif args.cmd == "stats":
        print(json.dumps(dbm.stats(conn), indent=2))
    elif args.cmd == "eval":
        from .core.evaluation import run_eval
        rep = run_eval(conn); print(rep["summary"]); return 0 if rep["failed"] == 0 else 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
